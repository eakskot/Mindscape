#!/usr/bin/env python3
"""
Generates the village cloud sprite sheet (for the zone clouds - CloudLayer.tsx lives on
the `archive/zones-clouds` branch; nothing on main draws these yet).

    python3 scripts/generate-clouds.py

Writes:
  src/assets/sprites/clouds/clouds.png        - the sheet (replace freely with hand-made art)
  src/game/village/cloudSheet.generated.ts    - each sprite's rect in the sheet

Pixel art at the village's native density (1 sheet pixel = 1 world pixel,
same as the 16x16 tiles): hard edges, no anti-aliasing, a 4-colour palette.
Opacity is NOT baked in - every pixel is fully opaque; CloudLayer sets
per-sprite opacity at draw time.

Hand-editing later (Piskel/Aseprite): keep the sheet at the same path and
keep the rects in cloudSheet.generated.ts in sync (or edit SPRITES below and
re-run - the script is deterministic, seeded).
"""
import math
import os
import random

from PIL import Image

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
OUT_PNG = os.path.join(ROOT, "src/assets/sprites/clouds/clouds.png")
OUT_TS = os.path.join(ROOT, "src/game/village/cloudSheet.generated.ts")

WHITE = (255, 255, 255, 255)
LIGHT = (220, 228, 238, 255)   # light blue-grey
SHADE = (169, 182, 200, 255)   # darker blue-grey shadow
EDGE = (125, 139, 163, 255)    # outline-ish edge tone

# (name, width, height, seed)
SPRITES = [
    ("cloud_s1", 48, 32, 11),
    ("cloud_s2", 48, 32, 23),
    ("cloud_m1", 64, 40, 37),
    ("cloud_m2", 64, 40, 41),
    ("cloud_l1", 96, 56, 53),
    ("cloud_l2", 96, 56, 67),
]
SHADOW = ("shadow", 64, 16)
PAD = 2


def cloud_mask(w, h, seed):
    """Union of overlapping ellipses: a bumpy row of bottom puffs plus a taller crown."""
    rng = random.Random(seed)
    mask = [[False] * w for _ in range(h)]
    base_y = h - 2  # lowest pixel row a puff may reach
    blobs = []

    def add(cx, r, lift):
        rx = r * 1.15
        cx = min(max(cx, rx + 1), w - rx - 1)  # keep the whole puff inside the sprite
        cy = base_y - r - lift
        blobs.append((cx, cy, r))

    n = max(3, w // 14)
    for i in range(n):
        r = rng.uniform(h * 0.20, h * 0.26)
        add(w * (i + 0.5) / n + rng.uniform(-2, 2), r, rng.uniform(0, 2))
    for _ in range(max(2, w // 30)):
        r = rng.uniform(h * 0.30, h * 0.38)
        add(rng.uniform(w * 0.3, w * 0.7), r, rng.uniform(h * 0.06, h * 0.14))
    for _ in range(2):
        r = rng.uniform(h * 0.20, h * 0.27)
        add(rng.uniform(w * 0.2, w * 0.8), r, rng.uniform(h * 0.22, h * 0.32))
    for y in range(h):
        for x in range(w):
            px, py = x + 0.5, y + 0.5
            for cx, cy, r in blobs:
                if ((px - cx) / (r * 1.15)) ** 2 + ((py - cy) / r) ** 2 <= 1:
                    mask[y][x] = True
                    break
    return mask


def shade_cloud(mask):
    h, w = len(mask), len(mask[0])
    img = Image.new("RGBA", (w, h), (0, 0, 0, 0))
    inside = lambda x, y: 0 <= x < w and 0 <= y < h and mask[y][x]
    for x in range(w):
        col = [y for y in range(h) if mask[y][x]]
        if not col:
            continue
        top, bottom = min(col), max(col)
        span = bottom - top + 1
        for y in col:
            t = (y - top) / max(1, span - 1)  # 0 at the top of this column, 1 at the bottom
            if t > 0.78:
                c = SHADE
            elif t > 0.58:
                c = LIGHT
            else:
                c = WHITE
            # outline: bottom/right edges get the edge tone, top/left the light tone
            if not inside(x, y + 1) or not inside(x + 1, y) or (t > 0.45 and not inside(x - 1, y)):
                c = EDGE
            elif not inside(x, y - 1) or not inside(x - 1, y):
                c = LIGHT if t > 0.3 else WHITE
            img.putpixel((x, y), c)
    return img


def shadow_sprite(w, h):
    img = Image.new("RGBA", (w, h), (0, 0, 0, 0))
    for y in range(h):
        for x in range(w):
            if ((x + 0.5 - w / 2) / (w / 2)) ** 2 + ((y + 0.5 - h / 2) / (h / 2)) ** 2 <= 1:
                img.putpixel((x, y), EDGE)
    return img


def main():
    images = [(name, shade_cloud(cloud_mask(w, h, seed))) for name, w, h, seed in SPRITES]
    images.append((SHADOW[0], shadow_sprite(SHADOW[1], SHADOW[2])))
    sheet_w = sum(img.width for _, img in images) + PAD * (len(images) + 1)
    sheet_h = max(img.height for _, img in images) + PAD * 2
    sheet = Image.new("RGBA", (sheet_w, sheet_h), (0, 0, 0, 0))
    rects = []
    x = PAD
    for name, img in images:
        sheet.paste(img, (x, PAD))
        rects.append((name, x, PAD, img.width, img.height))
        x += img.width + PAD
    os.makedirs(os.path.dirname(OUT_PNG), exist_ok=True)
    sheet.save(OUT_PNG)

    lines = [
        "/**",
        " * GENERATED by scripts/generate-clouds.py - re-run it (or hand-edit these",
        " * rects to match a hand-drawn src/assets/sprites/clouds/clouds.png).",
        " */",
        "",
        "export type CloudSpriteRect = { x: number; y: number; width: number; height: number };",
        "",
        "/** Every cloud variant, smallest first. */",
        "export const CLOUD_VARIANTS: CloudSpriteRect[] = [",
    ]
    for name, rx, ry, rw, rh in rects:
        if name != SHADOW[0]:
            lines.append(f"  {{ x: {rx}, y: {ry}, width: {rw}, height: {rh} }}, // {name}")
    lines.append("];")
    lines.append("")
    sname, sx, sy, sw, sh = rects[-1]
    lines.append("/** The soft ellipse drawn under each cloud (scaled to the cloud's width). */")
    lines.append(f"export const CLOUD_SHADOW: CloudSpriteRect = {{ x: {sx}, y: {sy}, width: {sw}, height: {sh} }};")
    lines.append("")
    with open(OUT_TS, "w") as f:
        f.write("\n".join(lines))
    print(f"Wrote {OUT_PNG} ({sheet_w}x{sheet_h}) and {OUT_TS}")


if __name__ == "__main__":
    main()
